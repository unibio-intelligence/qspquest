report_path <- Sys.getenv("QSPQUEST_R_REPORT")
if (!nzchar(report_path)) stop("QSPQUEST_R_REPORT must name a report file")
# Installed-package scientific checks; no timing claims.
.libPaths(c(Sys.getenv("QSPQUEST_R_LIBRARY"), .libPaths()))
library(qspquest)
library(jsonlite)
root <- normalizePath(Sys.getenv("QSPQUEST_ROOT", "."))
read_json_text <- function(path) paste(readLines(file.path(root,path),warn=FALSE),collapse="\n")
model <- compile_model(read_json_text("conformance/models/synthetic-one-compartment.json"))
sensitivity <- fromJSON(read_json_text("conformance/requests/synthetic-sensitivity.json"),simplifyVector=FALSE)
result <- simulate_model(model,sensitivity$run)
frame <- result_data_frame(result)
expected <- ifelse(frame$TIME==0 & frame$SIDE=="pre",0,2*exp(-.1*frame$TIME))
stopifnot(max(abs(frame$VALUE-expected))<1e-8,all(frame$UNIT=="mg/L"),identical(attr(frame,"execution_identity"),result$identity))
missing <- result;missing$outputs[[1]]$values[2] <- list(NULL)
stopifnot(nrow(result_data_frame(missing))==nrow(frame),is.na(result_data_frame(missing)$VALUE[2]))
fit_request <- fromJSON(read_json_text("conformance/requests/synthetic-fit.json"),simplifyVector=FALSE)
fit <- fit_model(model,fit_request)
stopifnot(fit$fit$status=="converged",abs(fit$fit$parameters$cl$value-.6)<1e-5,abs(fit$fit$parameters$v$value-4.5)<1e-5)
second <- fit_request$problem$request$objective
second$simulation$run$regimen$administrations[[1]]$amount$value <- 12
second$observations <- lapply(second$observations,function(o){o$value$value<-2*o$value$value;o})
pooled_request <- list(schema=fit_request$schema,problem=list(kind="pooled",request=list(fit=fit_request$problem$request,additional_subjects=list(second))))
pooled <- fit_model(model,pooled_request)
stopifnot(pooled$fit$status=="converged",abs(pooled$fit$parameters$v$value-4.5)<1e-5)
scan <- scan_model(model,read_json_text("conformance/requests/synthetic-scan.json"))
stopifnot(length(scan$results)==3)
morris <- morris_model(model,read_json_text("conformance/requests/synthetic-morris.json"))
stopifnot(length(morris$result$effects)==2,morris$design$seed==42)
bad <- sensitivity$run;bad$parameters<-list(cl=list(value=1,unit="h"))
failure <- tryCatch({simulate_model(model,bad);NULL},error=function(e){stopifnot(inherits(e,"qspquest_error"),e$code=="unit");conditionMessage(e)})
stopifnot(!is.null(failure),nzchar(failure))
stopifnot(identical(simulate_model(model,sensitivity$run),result))
limited <- fit_request;limited$problem$request$max_evaluations<-1
stopifnot(fit_model(model,limited)$fit$status=="evaluation_limit")
write_json(list(r_version=R.version.string,simulation=result,fit=fit,pooled=pooled,scan=scan,morris=morris,error=failure,data_frame_rows=nrow(frame),recovery=TRUE),report_path,auto_unbox=TRUE,digits=NA,pretty=TRUE,null="null")
cat("R simulation, individual/pooled fit, scan, Morris, data-frame and recovery checks passed\n")
