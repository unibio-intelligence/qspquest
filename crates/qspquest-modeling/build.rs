use sha2::{Digest, Sha256};
use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};
fn sources(path: &Path, files: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(path).expect("source directory") {
        let path = entry.expect("source entry").path();
        if path.is_dir() {
            sources(&path, files);
        } else if path.extension().is_some_and(|s| s == "rs") {
            files.push(path);
        }
    }
}
fn all_files(path: &Path, files: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(path).expect("vendored dependency directory") {
        let path = entry.expect("vendored dependency entry").path();
        if path.is_dir() {
            // Build artifacts and Git metadata are not dependency source.
            // They can change concurrently during dependency tests.
            if path
                .file_name()
                .is_some_and(|name| name == "target" || name == ".git")
            {
                continue;
            }
            all_files(&path, files);
        } else if path.is_file() {
            // The vendored workspace lock is generated by dependency tests;
            // QSPQuest's authoritative lockfile is hashed separately above.
            if path.file_name().is_some_and(|name| name == "Cargo.lock") {
                continue;
            }
            files.push(path);
        }
    }
}
fn relative_source_name(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .expect("source path within workspace")
        .components()
        .map(|part| part.as_os_str().to_str().expect("UTF-8 source path"))
        .collect::<Vec<_>>()
        .join("/")
}
fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../..");
    let mut files = Vec::new();
    for directory in [
        "crates/qspquest-core/src",
        "crates/qspquest-modeling/src",
        "bindings/wasm/src",
    ] {
        let dir = root.join(directory);
        println!("cargo:rerun-if-changed={}", dir.display());
        sources(&dir, &mut files);
    }
    for file in [
        "Cargo.toml",
        "Cargo.lock",
        ".cargo/config.toml",
        "crates/qspquest-core/Cargo.toml",
        "crates/qspquest-modeling/Cargo.toml",
        "bindings/wasm/Cargo.toml",
        "bindings/mcp/src/core/compute.rs",
        "crates/qspquest-modeling/build.rs",
        "vendor/DIFFSOL-PROVENANCE.md",
    ] {
        files.push(root.join(file));
    }
    files.sort();
    let mut hash = Sha256::new();
    for path in files {
        println!("cargo:rerun-if-changed={}", path.display());
        let relative = relative_source_name(&root, &path);
        let relative = relative.as_bytes();
        let data = fs::read(&path).expect("source bytes");
        hash.update((relative.len() as u64).to_be_bytes());
        hash.update(relative);
        hash.update((data.len() as u64).to_be_bytes());
        hash.update(data);
    }
    let vendored_root = root.join("vendor/diffsol");
    println!("cargo:rerun-if-changed={}", vendored_root.display());
    let mut vendored_files = Vec::new();
    all_files(&vendored_root, &mut vendored_files);
    vendored_files.sort();
    let mut vendored_hash = Sha256::new();
    for path in vendored_files {
        println!("cargo:rerun-if-changed={}", path.display());
        let relative = relative_source_name(&root, &path);
        let relative = relative.as_bytes();
        let data = fs::read(&path).expect("vendored dependency bytes");
        for digest in [&mut hash, &mut vendored_hash] {
            digest.update((relative.len() as u64).to_be_bytes());
            digest.update(relative);
            digest.update((data.len() as u64).to_be_bytes());
            digest.update(&data);
        }
    }
    println!(
        "cargo:rustc-env=QSPQUEST_DIFFSOL_SOURCE_SHA256={:x}",
        vendored_hash.finalize()
    );
    println!(
        "cargo:rustc-env=QSPQUEST_SOURCE_SHA256=sha256:{:x}",
        hash.finalize()
    );
    for key in ["TARGET", "PROFILE"] {
        println!("cargo:rustc-env=QSPQUEST_{key}={}", env::var(key).unwrap());
    }
    println!("cargo:rerun-if-env-changed=CARGO_ENCODED_RUSTFLAGS");
    println!(
        "cargo:rustc-env=QSPQUEST_RUSTFLAGS_SHA256=sha256:{:x}",
        Sha256::digest(
            env::var("CARGO_ENCODED_RUSTFLAGS")
                .unwrap_or_default()
                .as_bytes()
        )
    );
    let rustc = Command::new(env::var("RUSTC").unwrap())
        .arg("--version")
        .output()
        .expect("rustc version");
    assert!(rustc.status.success());
    println!(
        "cargo:rustc-env=QSPQUEST_RUSTC_VERSION={}",
        String::from_utf8(rustc.stdout).unwrap().trim()
    );
}
